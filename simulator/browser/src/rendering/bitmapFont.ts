export interface BitmapMetrics {
  pixel: number;
  glyphWidth: number;
  glyphHeight: number;
  advance: number;
}

export function bitmapMetrics(fontHeight: number): BitmapMetrics {
  const pixel = Math.max(1, Math.floor(fontHeight / 7));
  return {
    pixel,
    glyphWidth: 5 * pixel,
    glyphHeight: 7 * pixel,
    advance: 6 * pixel
  };
}

export function measureBitmapText(text: string, fontHeight: number): number {
  const metrics = bitmapMetrics(fontHeight);
  return text.length === 0 ? 0 : (text.length - 1) * metrics.advance + metrics.glyphWidth;
}

export function drawBitmapText(context: CanvasRenderingContext2D, text: string, x: number, y: number, fontHeight: number): void {
  const metrics = bitmapMetrics(fontHeight);
  let cursor = x;

  for (const char of text) {
    drawGlyph(context, glyphFor(char), cursor, y - metrics.glyphHeight, metrics.pixel);
    cursor += metrics.advance;
  }
}

export function glyphFor(char: string): string[] {
  const normalized = char.toUpperCase();
  return GLYPHS[normalized] ?? fallbackGlyph(char);
}

function drawGlyph(context: CanvasRenderingContext2D, glyph: string[], x: number, y: number, pixel: number): void {
  glyph.forEach((row, rowIndex) => {
    [...row].forEach((cell, colIndex) => {
      if (cell === "1") context.fillRect(x + colIndex * pixel, y + rowIndex * pixel, pixel, pixel);
    });
  });
}

function fallbackGlyph(char: string): string[] {
  const code = char.charCodeAt(0);
  return Array.from({ length: 7 }, (_, row) => (
    Array.from({ length: 5 }, (_, col) => ((code >> ((row + col) % 7)) & 1 ? "1" : "0")).join("")
  ));
}
